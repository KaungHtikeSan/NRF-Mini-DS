import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "tokens", "source");
const generated = path.join(root, "generated");
const validateOnly = process.argv.includes("--validate");
const aliases = { "border-seprator": "borderSeparator" };
const readJson = async (file) => JSON.parse(await readFile(path.join(source, file), "utf8"));
const developerName = (token) => aliases[token] || token.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const cssName = (token) => token === "border-seprator" ? "border-separator" : token;
const px = (value) => {
  const result = /^(-?\d+(?:\.\d+)?)px$/.exec(value);
  if (!result) throw new Error("Expected px value: " + value);
  return Number(result[1]);
};
const percent = (value) => {
  const result = /^(-?\d+(?:\.\d+)?)%$/.exec(value);
  if (!result) throw new Error("Expected percentage value: " + value);
  return Number(result[1]);
};
const quoted = (value) => JSON.stringify(value);
const androidHex = (value) => "0xFF" + value.slice(1).toUpperCase();

function assertTokens(colors, typography, spacing, modes) {
  if (!modes.length || !colors.length || !typography.length || !spacing.length) throw new Error("Token sources cannot be empty.");
  for (const [label, values] of [["color", colors], ["typography", typography], ["spacing", spacing]]) {
    const tokens = values.map((value) => value.token);
    if (new Set(tokens).size !== tokens.length) throw new Error("Duplicate " + label + " token.");
  }
  colors.forEach((color) => {
    if (color.type !== "color" || !/^#[0-9a-fA-F]{6}$/.test(color.value)) throw new Error("Invalid color: " + color.token);
  });
  typography.forEach((style) => {
    if (style.type !== "text" || !/^\d+$/.test(style.fontWeight)) throw new Error("Invalid typography: " + style.token);
    px(style.fontSize); px(style.lineHeight); percent(style.letterSpacing);
  });
  spacing.forEach((token, index) => {
    if (token.token !== "spacing-" + (index + 1) || px(token.value) !== (index + 1) * 4) {
      throw new Error("Spacing must be a contiguous 4px scale: " + token.token);
    }
  });
}

function webCss(mode, colors, typography, spacing) {
  const declarations = [];
  colors.forEach((color) => declarations.push("  --color-" + cssName(color.token) + ": " + color.value + ";"));
  spacing.forEach((token) => declarations.push("  --" + token.token + ": " + token.value + ";"));
  typography.forEach((style) => {
    ["font-family", "font-weight", "font-size", "line-height", "letter-spacing"].forEach((property) => {
      const key = property.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
      const value = property === "font-family" ? quoted(style.fontFamily) : style[key];
      declarations.push("  --typography-" + style.token + "-" + property + ": " + value + ";");
    });
  });
  const modeName = mode.name.toLowerCase().replace(/[^a-z0-9]+/g, "-");
  const classes = typography.map((style) => [
    ".nrf-typography-" + style.token + " {",
    "  font-family: var(--typography-" + style.token + "-font-family);",
    "  font-size: var(--typography-" + style.token + "-font-size);",
    "  font-weight: var(--typography-" + style.token + "-font-weight);",
    "  line-height: var(--typography-" + style.token + "-line-height);",
    "  letter-spacing: var(--typography-" + style.token + "-letter-spacing);",
    "}",
  ].join("\n")).join("\n\n");
  return ["/* Generated by design-system/scripts/generate-tokens.mjs. Do not edit. */", ":root,", '[data-nrf-mode="' + modeName + '"] {', declarations.join("\n"), "}", "", classes, ""].join("\n");
}

function webTypeScript(collectionName, mode, colors, typography, spacing) {
  const colorValues = Object.fromEntries(colors.map((color) => [developerName(color.token), color.value]));
  const colorMetadata = Object.fromEntries(colors.map((color) => [developerName(color.token), { figmaName: color.name, figmaToken: color.token, value: color.value }]));
  const typographyValues = Object.fromEntries(typography.map((style) => [developerName(style.token), {
    figmaName: style.name, figmaToken: style.token, fontFamily: style.fontFamily, fontWeight: Number(style.fontWeight),
    fontSize: style.fontSize, lineHeight: style.lineHeight, letterSpacing: style.letterSpacing,
  }]));
  const spacingValues = Object.fromEntries(spacing.map((token) => [developerName(token.token), token.value]));
  return [
    "/* Generated by design-system/scripts/generate-tokens.mjs. Do not edit. */",
    "export const nrfColorCollection = " + JSON.stringify({ name: collectionName, mode: mode.name }, null, 2) + " as const;",
    "export const nrfColors = " + JSON.stringify(colorValues, null, 2) + " as const;",
    "export const nrfColorMetadata = " + JSON.stringify(colorMetadata, null, 2) + " as const;",
    "export const nrfSpacing = " + JSON.stringify(spacingValues, null, 2) + " as const;",
    "export const nrfTypography = " + JSON.stringify(typographyValues, null, 2) + " as const;",
    "",
  ].join("\n\n");
}

function swift(colors, typography, spacing) {
  const colorMembers = colors.map((color) => "  public static let " + developerName(color.token) + " = UIColor(nrfHex: " + quoted(color.value) + ")").join("\n");
  const swiftUiMembers = colors.map((color) => "  public static let " + developerName(color.token) + " = Color(uiColor: NRFColors." + developerName(color.token) + ")").join("\n");
  const typeMembers = typography.map((style) => "  public static let " + developerName(style.token) + " = NRFTextStyle(fontFamily: " + quoted(style.fontFamily) + ", fontWeight: " + style.fontWeight + ", fontSize: " + px(style.fontSize) + ", lineHeight: " + px(style.lineHeight) + ", tracking: " + (px(style.fontSize) * percent(style.letterSpacing) / 100) + ")").join("\n");
  const spacingMembers = spacing.map((token) => "  public static let " + developerName(token.token) + ": CGFloat = " + px(token.value)).join("\n");
  return [
    "// Generated by design-system/scripts/generate-tokens.mjs. Do not edit.",
    "import SwiftUI", "import UIKit", "",
    "public enum NRFColors {", colorMembers, "}", "",
    "public enum NRFSwiftUIColors {", swiftUiMembers, "}", "",
    "public enum NRFSpacing {", spacingMembers, "}", "",
    "public struct NRFTextStyle {",
    "  public let fontFamily: String; public let fontWeight: Int; public let fontSize: CGFloat; public let lineHeight: CGFloat; public let tracking: CGFloat",
    "  public var font: Font { Font.custom(fontFamily, size: fontSize).weight(fontWeight == 700 ? .bold : fontWeight == 500 ? .medium : .regular) }",
    "}", "",
    "public enum NRFTypography {", typeMembers, "}", "",
    "public extension View {",
    "  func nrfTextStyle(_ style: NRFTextStyle) -> some View { font(style.font).tracking(style.tracking).lineSpacing(max(0, style.lineHeight - style.fontSize)) }",
    "}", "",
    "public extension UIColor {",
    "  convenience init(nrfHex: String) { let value = UInt64(nrfHex.dropFirst(), radix: 16) ?? 0; self.init(red: CGFloat((value >> 16) & 0xFF) / 255, green: CGFloat((value >> 8) & 0xFF) / 255, blue: CGFloat(value & 0xFF) / 255, alpha: 1) }",
    "}", "",
  ].join("\n");
}

function kotlin(colors, typography, spacing) {
  const colorMembers = colors.map((color) => "  val " + developerName(color.token) + " = Color(" + androidHex(color.value) + ")").join("\n");
  const typeMembers = typography.map((style) => "  val " + developerName(style.token) + " = NRFTextStyleSpec(" + quoted(style.fontFamily) + ", FontWeight(" + style.fontWeight + "), " + px(style.fontSize) + ".sp, " + px(style.lineHeight) + ".sp, " + (percent(style.letterSpacing) / 100) + ".em)").join("\n");
  const spacingMembers = spacing.map((token) => "  val " + developerName(token.token) + " = " + px(token.value) + ".dp").join("\n");
  return [
    "// Generated by design-system/scripts/generate-tokens.mjs. Do not edit.",
    "package com.nrf.designsystem.tokens", "",
    "import androidx.compose.ui.graphics.Color", "import androidx.compose.ui.text.TextStyle", "import androidx.compose.ui.text.font.FontFamily", "import androidx.compose.ui.text.font.FontWeight", "import androidx.compose.ui.unit.TextUnit", "import androidx.compose.ui.unit.dp", "import androidx.compose.ui.unit.em", "import androidx.compose.ui.unit.sp", "",
    "object NRFColors {", colorMembers, "}", "",
    "object NRFSpacing {", spacingMembers, "}", "",
    "data class NRFTextStyleSpec(val fontFamilyName: String, val fontWeight: FontWeight, val fontSize: TextUnit, val lineHeight: TextUnit, val letterSpacing: TextUnit) {",
    "  fun toTextStyle(fontFamily: FontFamily) = TextStyle(fontFamily = fontFamily, fontWeight = fontWeight, fontSize = fontSize, lineHeight = lineHeight, letterSpacing = letterSpacing)",
    "}", "",
    "object NRFTypography {", typeMembers, "}", "",
  ].join("\n");
}

const colorsJson = await readJson("colors.json");
const typographyJson = await readJson("typography.json");
const spacingJson = await readJson("spacing.json");
const collectionName = Object.keys(colorsJson.collections)[0];
const collection = colorsJson.collections[collectionName];
const mode = collection.modes[0];
const colors = collection.variables.colors;
const typography = typographyJson.styles.textStyles;
const spacing = spacingJson.tokens;
assertTokens(colors, typography, spacing, collection.modes);

const outputs = [
  ["web/tokens.css", webCss(mode, colors, typography, spacing)],
  ["web/tokens.ts", webTypeScript(collectionName, mode, colors, typography, spacing)],
  ["ios/NRFTokens.swift", swift(colors, typography, spacing)],
  ["android/NRFTokens.kt", kotlin(colors, typography, spacing)],
  ["token-manifest.json", JSON.stringify({ collection: collectionName, mode: mode.name, colors, typography, spacing }, null, 2) + "\n"],
];

if (validateOnly) {
  for (const [relative, content] of outputs) {
    let current;
    try { current = await readFile(path.join(generated, relative), "utf8"); } catch { throw new Error("Missing generated output: " + relative); }
    if (current !== content) throw new Error("Stale generated output: " + relative);
  }
  console.log("Validated " + colors.length + " colors, " + typography.length + " typography styles, and " + spacing.length + " spacing tokens.");
} else {
  await Promise.all(outputs.map(async ([relative, content]) => {
    const target = path.join(generated, relative);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content, "utf8");
  }));
  console.log("Generated " + outputs.length + " platform token files.");
}
